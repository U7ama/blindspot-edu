# ---------------------------------------------------------------------------
# Shared result types
# ---------------------------------------------------------------------------


class GroundingIssue(BaseModel):
    """One grounding problem found in a generated pipeline item.

    The `detail` text is written to be fed back into the generator's prompt
    on a retry attempt, so it always identifies the offending item's content,
    not just its position.
    """
    item_kind: str = Field(..., description="'phase', 'quiz', or 'gap'")
    item_index: int = Field(
        ..., description="Index into the item list (plan.phases / quizzes / gaps)"
    )
    code: str = Field(
        ..., description="Machine-readable reason, e.g. 'timestamp_out_of_range'"
    )
    detail: str = Field(
        ..., description="Human-readable explanation, fed back to the LLM on retry"
    )


class RelevanceVerdict(BaseModel):
    """Whether a live-session question relates to the lecture being taught."""
    is_relevant: bool
    reason: str = ""
    redirect_message: str = Field(
        default="",
        description="Short spoken deflection used when the question is off-topic",
    )


# ---------------------------------------------------------------------------
# Lexical-overlap helpers (cheap first line of defense, no LLM involved)
# ---------------------------------------------------------------------------

_STOPWORDS = frozenset({
    "the", "a", "an", "and", "or", "but", "if", "then", "else", "for", "to",
    "of", "in", "on", "at", "by", "with", "from", "as", "is", "are", "was",
    "were", "be", "been", "being", "it", "its", "this", "that", "these",
    "those", "you", "your", "we", "our", "they", "their", "he", "she", "his",
    "her", "i", "me", "my", "us", "them", "do", "does", "did", "done",
    "have", "has", "had", "not", "no", "so", "such", "what", "which", "who",
    "whom", "when", "where", "why", "how", "can", "could", "will", "would",
    "should", "may", "might", "must", "about", "into", "over", "under",
    "between", "through", "during", "before", "after", "again", "there",
    "here", "all", "any", "both", "each", "few", "more", "most", "other",
    "some", "only", "own", "same", "than", "too", "very", "just", "because",
    "while", "let", "lets", "now", "also", "like", "get", "got", "make",
    "makes", "made", "thing", "things", "something", "anything", "everything",
    "really", "actually", "basically", "going", "know", "think", "want",
    "see", "look", "say", "said", "tell", "told", "question", "answer",
    "explain", "explanation", "mean", "means", "please",
})

# Below this ratio of shared content-word vocabulary, a generated item is
# almost certainly about something the lecture never said. Kept deliberately
# low — paraphrased teaching scripts legitimately introduce new words, so
# this check exists to catch wholesale hallucination, not loose wording.
_MIN_GROUNDING_OVERLAP = 0.2

# A question whose content words overlap the lecture vocabulary at or above
# this ratio is clearly on-topic and skips the LLM classifier entirely.
_RELEVANCE_OVERLAP_THRESHOLD = 0.34


def _tokenize(text: str) -> set[str]:
    """Lowercase word tokens with stopwords and very short tokens removed."""
    return {
        tok
        for tok in re.findall(r"[a-z0-9]+", (text or "").lower())
        if len(tok) > 2 and tok not in _STOPWORDS
    }


def _transcript_vocabulary(transcript: list[TranscriptSegment]) -> set[str]:
    """All content words appearing anywhere in the transcript."""
    vocab: set[str] = set()
    for seg in transcript:
        vocab |= _tokenize(seg.text)
    return vocab


def _lexical_overlap(text: str, vocabulary: set[str]) -> float:
    """Fraction of `text`'s content words that appear in `vocabulary`.

    Returns 1.0 when either side has no usable tokens — there is nothing to
    compare against, so we fail open rather than flag every item.
    """
    tokens = _tokenize(text)
    if not tokens or not vocabulary:
        return 1.0
    return len(tokens & vocabulary) / len(tokens)


def _format_transcript_excerpt(
    transcript: list[TranscriptSegment],
    max_chars: int = 6000,
) -> str:
    """Simple timestamped transcript block for validator prompts.

    Lighter than planning.py's `_format_transcript` (no segment merging) —
    the judge only needs to read what was said, not plan around it.
    """
    lines = [f"[{s.start:.1f}s - {s.end:.1f}s] {s.text}" for s in transcript]
    block = "\n".join(lines)
    if len(block) > max_chars:
        block = block[:max_chars] + "\n... [transcript continues]"
    return block


# ---------------------------------------------------------------------------
# 1a. Deterministic grounding checks
# ---------------------------------------------------------------------------

_TIMESTAMP_TOLERANCE_S = 1.0


def _check_time_range(
    tr: TimeRange,
    item_kind: str,
    item_index: int,
    item_label: str,
    transcript: list[TranscriptSegment],
    transcript_end: float,
) -> list[GroundingIssue]:
    """Validates one cited TimeRange against the actual transcript bounds."""
    issues: list[GroundingIssue] = []

    if tr.end <= tr.start:
        issues.append(GroundingIssue(
            item_kind=item_kind,
            item_index=item_index,
            code="malformed_time_range",
            detail=f"{item_label}: source timestamp start ({tr.start:.1f}s) "
                   f"is not before its end ({tr.end:.1f}s).",
        ))
        return issues  # further checks are meaningless on a broken range

    if tr.end > transcript_end + _TIMESTAMP_TOLERANCE_S:
        issues.append(GroundingIssue(
            item_kind=item_kind,
            item_index=item_index,
            code="timestamp_out_of_range",
            detail=f"{item_label}: source timestamp {tr.start:.1f}s-{tr.end:.1f}s "
                   f"lies outside the transcript (0s-{transcript_end:.1f}s).",
        ))
    elif not any(seg.end >= tr.start and seg.start <= tr.end for seg in transcript):
        issues.append(GroundingIssue(
            item_kind=item_kind,
            item_index=item_index,
            code="timestamp_no_transcript_overlap",
            detail=f"{item_label}: source timestamp {tr.start:.1f}s-{tr.end:.1f}s "
                   f"overlaps no actual transcript segment.",
        ))

    return issues


# ---------------------------------------------------------------------------
# 1b. LLM grounding judge
# ---------------------------------------------------------------------------


class _LLMGroundingVerdict(BaseModel):
    item_index: int
    grounded: bool
    reason: str = ""


class _LLMGroundingResponse(BaseModel):
    verdicts: list[_LLMGroundingVerdict] = Field(default_factory=list)


_GROUNDING_JUDGE_SYSTEM_PROMPT = """\
You are a strict fact-checking judge for an educational pipeline. You are
given a lecture transcript and a list of content items that an AI generated
from it (teaching phases, quiz questions, or gap concepts).

For EACH item, decide whether it is GROUNDED in the transcript:
- grounded = true: the item's claims, concepts, and facts are actually
  discussed or clearly implied by the transcript (and, where a source
  excerpt is cited, the excerpt supports the item). Paraphrasing and
  pedagogical rewording of transcript content still counts as grounded.
- grounded = false: the item invents content that is not in the transcript,
  or its cited excerpt does not support it. Introducing topics the lecture
  never touches is NOT grounded, even if they are topically adjacent.

Respond with a JSON object in this exact shape:
{
  "verdicts": [
    {"item_index": 0, "grounded": true, "reason": "one short sentence"}
  ]
}
Include exactly one verdict per item, using the item indices given.
"""


def _judge_items_with_llm(
    item_kind: str,
    candidates: list[tuple[int, str]],
    transcript: list[TranscriptSegment],
) -> list[GroundingIssue]:
    """One batched LLM call judging candidate items against the transcript.

    `candidates` is a list of (original_index, rendered_item_text) pairs;
    original indices are preserved so verdicts map back to the caller's
    item list even after deterministic checks filtered some items out.
    Fail-open: a failed judge call accepts the items as-is.
    """
    if not candidates:
        return []

    transcript_block = _format_transcript_excerpt(transcript)
    if not transcript_block:
        return []  # nothing to judge against — fail open

    items_block = "\n\n".join(
        f"{item_kind.upper()} {idx}:\n{text}" for idx, text in candidates
    )
    user_prompt = f"TRANSCRIPT:\n{transcript_block}\n\nITEMS TO JUDGE:\n{items_block}"

    try:
        response = chat_completion(
            system_prompt=_GROUNDING_JUDGE_SYSTEM_PROMPT,
            user_prompt=user_prompt,
            temperature=0.1,
            max_tokens=1024,
            response_model=_LLMGroundingResponse,
        )
    except Exception as exc:
        print(f"[guardrails] grounding judge call failed ({exc}); accepting items as-is")
        return []

    valid_indices = {idx for idx, _ in candidates}
    issues: list[GroundingIssue] = []
    for verdict in response.verdicts:
        # Ignore hallucinated indices; items with no verdict are treated as
        # grounded (fail-open — we only remove content on a positive signal).
        if verdict.item_index not in valid_indices:
            continue
        if not verdict.grounded:
            issues.append(GroundingIssue(
                item_kind=item_kind,
                item_index=verdict.item_index,
                code="ungrounded_content",
                detail=f"{item_kind.capitalize()} #{verdict.item_index} is not "
                       f"grounded in the transcript: {verdict.reason}",
            ))
    return issues


