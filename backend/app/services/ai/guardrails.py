def _phase_judge_text(phase: Phase, transcript: list[TranscriptSegment]) -> str:
    """Renders a phase for the judge, including its cited source excerpt."""
    text = f"title: {phase.title}\nteaching_script: {phase.teaching_script}"
    excerpts: list[str] = []
    for tr in phase.source_timestamps:
        cited = [s.text for s in transcript if s.end >= tr.start and s.start <= tr.end]
        if cited:
            excerpts.append(" ".join(cited[:6]))
    if excerpts:
        text += "\ncited_excerpt: " + "\n".join(excerpts)[:1500]
    return text


def validate_plan(
    plan: LearningPlan,
    transcript: list[TranscriptSegment],
) -> list[GroundingIssue]:
    """Grounding-validation for a generated LearningPlan.

    Deterministic checks (timestamps, empty fields, duplicate orders,
    lexical overlap) run first; surviving phases go to the LLM judge.
    """
    vocab = _transcript_vocabulary(transcript)
    transcript_end = max((s.end for s in transcript), default=0.0)

    issues: list[GroundingIssue] = []
    failed: set[int] = set()
    seen_orders: set[int] = set()

    for idx, phase in enumerate(plan.phases):
        label = f"Phase '{phase.title}' (index {idx})"

        if phase.order in seen_orders:
            issues.append(GroundingIssue(
                item_kind="phase", item_index=idx, code="duplicate_phase_order",
                detail=f"{label}: phase order {phase.order} is used more than once.",
            ))
            failed.add(idx)
        seen_orders.add(phase.order)

        if not phase.title.strip() or not phase.teaching_script.strip():
            issues.append(GroundingIssue(
                item_kind="phase", item_index=idx, code="empty_field",
                detail=f"{label}: title and teaching_script must both be non-empty.",
            ))
            failed.add(idx)
            continue  # no point running the remaining checks on an empty phase

        for tr in phase.source_timestamps:
            tr_issues = _check_time_range(
                tr, "phase", idx, label, transcript, transcript_end
            )
            if tr_issues:
                issues.extend(tr_issues)
                failed.add(idx)

        overlap = _lexical_overlap(f"{phase.title}. {phase.teaching_script}", vocab)
        if overlap < _MIN_GROUNDING_OVERLAP:
            issues.append(GroundingIssue(
                item_kind="phase", item_index=idx, code="ungrounded_content",
                detail=f"{label}: shares almost no vocabulary with the transcript "
                       f"(overlap {overlap:.2f}) — likely not grounded in the lecture.",
            ))
            failed.add(idx)

    candidates = [
        (idx, _phase_judge_text(phase, transcript))
        for idx, phase in enumerate(plan.phases)
        if idx not in failed
    ]
    issues.extend(_judge_items_with_llm("phase", candidates, transcript))
    return issues


def validate_quizzes(
    quizzes: list[QuizItem],
    transcript: list[TranscriptSegment],
) -> list[GroundingIssue]:
    """Grounding-validation for generated quiz items.

    Deterministic checks: non-empty question, exactly 4 unique options,
    correct_answer matching one option character-for-character, timestamp
    sanity, and lexical overlap with the transcript.
    """
    vocab = _transcript_vocabulary(transcript)
    transcript_end = max((s.end for s in transcript), default=0.0)

    issues: list[GroundingIssue] = []
    failed: set[int] = set()

    for idx, quiz in enumerate(quizzes):
        label = f"Quiz question '{quiz.question[:60]}' (index {idx})"

        if not quiz.question.strip():
            issues.append(GroundingIssue(
                item_kind="quiz", item_index=idx, code="empty_field",
                detail=f"{label}: question text must be non-empty.",
            ))
            failed.add(idx)
            continue

        if quiz.correct_answer not in quiz.options:
            issues.append(GroundingIssue(
                item_kind="quiz", item_index=idx, code="answer_not_in_options",
                detail=f"{label}: correct_answer '{quiz.correct_answer[:60]}' is not "
                       f"an exact copy of one of the options.",
            ))
            failed.add(idx)

        if len(quiz.options) != 4 or len(set(quiz.options)) != len(quiz.options):
            issues.append(GroundingIssue(
                item_kind="quiz", item_index=idx, code="bad_options",
                detail=f"{label}: needs exactly 4 distinct options, "
                       f"got {len(quiz.options)}.",
            ))
            failed.add(idx)

        if quiz.source_timestamp:
            tr_issues = _check_time_range(
                quiz.source_timestamp, "quiz", idx, label, transcript, transcript_end
            )
            if tr_issues:
                issues.extend(tr_issues)
                failed.add(idx)

        combined = " ".join([quiz.question, *quiz.options, quiz.correct_answer])
        overlap = _lexical_overlap(combined, vocab)
        if overlap < _MIN_GROUNDING_OVERLAP:
            issues.append(GroundingIssue(
                item_kind="quiz", item_index=idx, code="ungrounded_content",
                detail=f"{label}: shares almost no vocabulary with the transcript "
                       f"(overlap {overlap:.2f}) — likely not grounded in the lecture.",
            ))
            failed.add(idx)

    candidates = [
        (idx, f"question: {q.question}\noptions: {q.options}\n"
              f"correct_answer: {q.correct_answer}")
        for idx, q in enumerate(quizzes)
        if idx not in failed
    ]
    issues.extend(_judge_items_with_llm("quiz", candidates, transcript))
    return issues


def validate_gaps(
    gaps: list[GapConcept],
    transcript: list[TranscriptSegment],
) -> list[GroundingIssue]:
    """Grounding-validation for detected gap concepts.

    A gap must name something the transcript actually mentions — otherwise
    the 'blind spot' itself is a hallucination.
    """
    vocab = _transcript_vocabulary(transcript)
    transcript_end = max((s.end for s in transcript), default=0.0)

    issues: list[GroundingIssue] = []
    failed: set[int] = set()

    for idx, gap in enumerate(gaps):
        label = f"Gap concept '{gap.name}' (index {idx})"

        if not gap.name.strip() or not gap.why_its_a_gap.strip():
            issues.append(GroundingIssue(
                item_kind="gap", item_index=idx, code="empty_field",
                detail=f"{label}: name and why_its_a_gap must both be non-empty.",
            ))
            failed.add(idx)
            continue

        if gap.source_timestamp:
            tr_issues = _check_time_range(
                gap.source_timestamp, "gap", idx, label, transcript, transcript_end
            )
            if tr_issues:
                issues.extend(tr_issues)
                failed.add(idx)

        overlap = _lexical_overlap(f"{gap.name}. {gap.why_its_a_gap}", vocab)
        if overlap < _MIN_GROUNDING_OVERLAP:
            issues.append(GroundingIssue(
                item_kind="gap", item_index=idx, code="ungrounded_content",
                detail=f"{label}: shares almost no vocabulary with the transcript "
                       f"(overlap {overlap:.2f}) — the lecture likely never "
                       f"mentions this concept.",
            ))
            failed.add(idx)

    candidates = [
        (idx, f"name: {g.name}\nwhy_its_a_gap: {g.why_its_a_gap}")
        for idx, g in enumerate(gaps)
        if idx not in failed
    ]
    issues.extend(_judge_items_with_llm("gap", candidates, transcript))
    return issues


def validate_grounding(
    plan: LearningPlan,
    quizzes: list[QuizItem],
    gaps: list[GapConcept],
    transcript: list[TranscriptSegment],
) -> list[GroundingIssue]:
    """Entry point: validate all generated pipeline content at once.

    The pipeline's retry wrapper validates per step instead; this composer
    exists for validating a complete (e.g. previously stored) result.
    """
    return (
        validate_plan(plan, transcript)
        + validate_quizzes(quizzes, transcript)
        + validate_gaps(gaps, transcript)
    )


# ---------------------------------------------------------------------------
# 1d. Retry-with-feedback wrapper
# ---------------------------------------------------------------------------


def _format_issues_for_retry(issues: list[GroundingIssue]) -> str:
    """Renders issues as a bullet list the generator prompt can act on."""
    return "\n".join(f"- [{issue.code}] {issue.detail}" for issue in issues)


def _filter_ungrounded(
    result: Any,
    issues: list[GroundingIssue],
) -> tuple[Any, int]:
    """Removes the flagged items from a generator result.

    Works on LearningPlan (filters .phases) and on plain lists (gaps,
    quizzes). Returns (filtered_result, removed_count).
    """
    bad_indices = {issue.item_index for issue in issues}
    if isinstance(result, LearningPlan):
        kept = [p for idx, p in enumerate(result.phases) if idx not in bad_indices]
        removed = len(result.phases) - len(kept)
        return result.model_copy(update={"phases": kept}), removed
    kept = [item for idx, item in enumerate(result) if idx not in bad_indices]
    return kept, len(result) - len(kept)


def with_grounding_retry(
    generate_fn: Callable[[Optional[str]], Any],
    validate_fn: Callable[[Any], list[GroundingIssue]],
    step_name: str,
    max_attempts: int = 2,
) -> tuple[Any, dict]:
    """Runs a pipeline generation step under grounding validation.

    Flow per attempt: generate -> validate. If issues are found and attempts
    remain, the issues are fed back into the generator via its `feedback`
    argument. After the final attempt, the offending items are filtered out
    and a warning is logged — this function NEVER raises, so a guardrail
    failure can never take the whole pipeline down with it.

    Args:
        generate_fn: Called as generate_fn(feedback); `feedback` is None on
            the first attempt and a rendered issue list afterwards.
        validate_fn: Called with the generated result, returns issues.
        step_name: For log lines, e.g. "plan".
        max_attempts: Total generation attempts (1 = validate once, no retry).

    Returns:
        (result, report) where report = {"attempts": n, "removed": m,
        "issues": [...]} for PipelineResult.validation_report.
    """
    feedback: Optional[str] = None
    result: Any = None
    issues: list[GroundingIssue] = []

    for attempt in range(1, max_attempts + 1):
        result = generate_fn(feedback)
        issues = validate_fn(result)
        if not issues:
            return result, {"attempts": attempt, "removed": 0, "issues": []}
        print(
            f"[guardrails] {step_name}: attempt {attempt} produced "
            f"{len(issues)} grounding issue(s)"
        )
        feedback = _format_issues_for_retry(issues)

    filtered, removed = _filter_ungrounded(result, issues)
    print(
        f"[guardrails] {step_name}: removed {removed} ungrounded item(s) "
        f"after {max_attempts} attempt(s)"
    )
    return filtered, {
        "attempts": max_attempts,
        "removed": removed,
        "issues": [issue.model_dump() for issue in issues],
    }


# ---------------------------------------------------------------------------
# 2. Input relevance validation (live tutoring session)
# ---------------------------------------------------------------------------


class _LLMRelevanceResponse(BaseModel):
    is_relevant: bool
    reason: str = ""
    redirect_message: str = ""


_RELEVANCE_SYSTEM_PROMPT = """\
You are a topic classifier for a live AI tutoring session. A student asked
a question while being taught a lecture. Decide whether the question is
RELEVANT to the lecture or the tutoring session.

RELEVANT means the question is about:
- the lecture's subject matter or any concept it touches (even loosely),
- the current lesson phase being taught,
- the tutoring session itself (e.g. "can you repeat that?", "what phase
  are we on?").

IRRELEVANT means the question is clearly about an unrelated domain the
lecture never touches (e.g. asking a neural-networks lecture for pizza
recommendations, sports scores, or homework in another subject).

If irrelevant, also write a warm, brief redirect_message (1-2 sentences,
spoken aloud by the tutor) that acknowledges the question and steers the
student back to the lecture topic. If relevant, leave redirect_message empty.

Respond with a JSON object in this exact shape:
{
  "is_relevant": true,
  "reason": "one short sentence",
  "redirect_message": ""
}
"""


def check_question_relevance(
    question: str,
    current_phase: Optional[Phase] = None,
    transcript_segments: Optional[list[TranscriptSegment]] = None,
) -> RelevanceVerdict:
    """Classifies whether a live-session question relates to the lecture.

    Two stages:
      1. Fast lexical heuristic — a question whose content words clearly
         overlap the lecture vocabulary is on-topic; no LLM call needed.
      2. LLM fallback classifier for everything else.

    Fail-open: any error in the classifier path treats the question as
    relevant — a broken guardrail must never silence a student.
    """
    clean_question = (question or "").strip()
    if not clean_question:
        return RelevanceVerdict(is_relevant=True, reason="empty question")

    # 1. Fast heuristic pre-check (no LLM call for obviously on-topic input).
    vocab: set[str] = set()
    if current_phase:
        vocab |= _tokenize(current_phase.title)
        vocab |= _tokenize(current_phase.teaching_script)
    for seg in (transcript_segments or [])[:50]:
        vocab |= _tokenize(seg.text)

    q_tokens = _tokenize(clean_question)
    if q_tokens and vocab:
        overlap = len(q_tokens & vocab) / len(q_tokens)
        if overlap >= _RELEVANCE_OVERLAP_THRESHOLD:
            return RelevanceVerdict(
                is_relevant=True,
                reason=f"lexical overlap {overlap:.2f} with lecture content",
            )

    # 2. LLM fallback classifier.
    context_lines: list[str] = []
    if current_phase:
        context_lines.append(f"Current lesson phase: {current_phase.title}")
        context_lines.append(f"What is being taught: {current_phase.teaching_script}")
    excerpt = _format_transcript_excerpt(transcript_segments or [], max_chars=2000)
    if excerpt:
        context_lines.append(f"Lecture transcript excerpt:\n{excerpt}")

    user_prompt = (
        "LECTURE CONTEXT:\n" + "\n\n".join(context_lines)
        + f"\n\nSTUDENT QUESTION:\n\"{clean_question}\""
    )

    try:
        response = chat_completion(
            system_prompt=_RELEVANCE_SYSTEM_PROMPT,
            user_prompt=user_prompt,
            temperature=0.0,
            max_tokens=150,
            response_model=_LLMRelevanceResponse,
        )
    except Exception as exc:
        print(f"[guardrails] relevance check failed ({exc}); treating question as relevant")
        return RelevanceVerdict(
            is_relevant=True,
            reason="relevance classifier unavailable; failing open",
        )

    return RelevanceVerdict(
        is_relevant=response.is_relevant,
        reason=response.reason,
        redirect_message=response.redirect_message,
    )
