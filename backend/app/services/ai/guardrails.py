"""
backend/ai/guardrails.py


Guardrails layer for the AI pipeline. Two responsibilities:

    1. Output grounding validation — verify that content generated by the
       planning pipeline (learning phases, quiz items, gap concepts) is
       actually grounded in the source lecture transcript, with a
       retry-with-feedback mechanism when validation fails.
    2. Input relevance validation — detect when a student's live-session
       question is unrelated to the lecture being taught, so it can be
       deflected gracefully instead of being answered as lecture content.

Design notes:
    - Deterministic checks run first (they're free); the LLM judge only
      sees items that pass them, which keeps token usage low.
    - Every failure mode degrades gracefully: the offline pipeline filters
      ungrounded items instead of crashing (mirroring the "never fail on
      the reduce step" philosophy in planning.py), and the live relevance
      check fails open — it answers anyway — when the classifier errors.
    - All LLM access goes through backend/ai/llm.py's chat_completion,
      same as every other AI module.

Requires: openai, pydantic >= 2
"""

